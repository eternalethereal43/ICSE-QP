export function getSubjectById(id: SubjectId): SubjectDefinition {
  const found = ICSE_SUBJECTS.find((s) => s.id === id);
  if (!found) {
    throw new Error(`Unknown ICSE subject: ${id}`);
  }
  return found;
}

export function getPaperBlueprint(subjectId: SubjectId, marks: PaperMarks): PaperBlueprint {
  const subject = getSubjectById(subjectId);
  return subject.blueprints[marks];
}

export function formatDuration(minutes: number): string {
  const hrs = Math.floor(minutes / 60);
  const mins = minutes % 60;
  if (hrs === 0) return `${mins} mins`;
  if (mins === 0) return hrs === 1 ? '1 hour' : `${hrs} hours`;
  return `${hrs} hr ${mins} mins`;
}
